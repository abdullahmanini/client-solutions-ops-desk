    fc.type, fc.title, fc.height, fc.width = "bar", "Funnel", 7, 13
    fc.add_data(Reference(ws, min_col=2, min_row=4, max_row=9), titles_from_data=True)
    fc.set_categories(Reference(ws, min_col=1, min_row=5, max_row=9))
    fc.legend = None
    fc.y_axis.scaling.orientation = "minMax"
    fc.x_axis.scaling.orientation = "maxMin"
    ws.add_chart(fc, "G3")
    header(ws, 12, ["CSM", "Eligible", "Pitched", "Adopted", "Pitch rate", "Adoption rate"])
    csms = [r[0] for r in rows(con, "SELECT csm_name FROM mart_auto_by_csm")]
    for i, c in enumerate(csms):
        rr = 13 + i
        ws.cell(row=rr, column=1, value=c).font = BODY
        ws.cell(row=rr, column=2, value=f'=COUNTIF({A("csm_name")},$A{rr})')
        ws.cell(row=rr, column=3, value=f'=COUNTIFS({A("csm_name")},$A{rr},{A("pitched")},1)')
        ws.cell(row=rr, column=4, value=f'=COUNTIFS({A("csm_name")},$A{rr},{A("adopted")},1)')
        ws.cell(row=rr, column=5, value=f"=IFERROR(C{rr}/B{rr},0)").number_format = PCT
        ws.cell(row=rr, column=6, value=f"=IFERROR(D{rr}/B{rr},0)").number_format = PCT
    end = 12 + len(csms)
    ws.conditional_formatting.add(f"E13:E{end}", CellIsRule(operator="lessThan", formula=["0.5"], font=Font(color=ACCENT, bold=True)))
    ws.cell(row=end + 2, column=1, value="Read: pitch coverage, not product fit, is the biggest gap. One book was pitched far less than the others.").font = NOTE
    widths(ws, [22, 12, 12, 14, 12, 14])

