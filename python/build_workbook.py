    ws = wb.create_sheet("Adoption", 2)
    title(ws, "Product adoption, last 4 weeks (Sep 7 - Oct 4)", "Adopted = at least the threshold spent on the product in weeks 23-26. Client accounts only.")
    ws["A3"], ws["B3"] = "Adoption threshold (USD, 4 weeks)", 500
