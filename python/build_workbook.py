import shutil
import sqlite3
import zipfile
from datetime import date
from pathlib import Path
from xml.sax.saxutils import escape

from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.comments import Comment
from openpyxl.formatting.rule import CellIsRule, DataBarRule, FormulaRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.table import Table, TableStyleInfo

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "outputs" / "desk.db"
OUT = ROOT / "outputs" / "client_solutions_ops_desk.xlsx"

F = "Arial"
INK = "111318"
ACCENT = "E8345C"
TEAL = "0FA3A3"
HEAD_FILL = PatternFill("solid", fgColor=INK)
SUB_FILL = PatternFill("solid", fgColor="EEF1F4")
INPUT_FONT = Font(name=F, size=10, color="0000FF")
BODY = Font(name=F, size=10)
BOLD = Font(name=F, size=10, bold=True)
HEAD = Font(name=F, size=10, bold=True, color="FFFFFF")
TITLE = Font(name=F, size=16, bold=True, color=INK)
NOTE = Font(name=F, size=9, italic=True, color="5B6270")
THIN = Border(bottom=Side(style="thin", color="D5DAE1"))
USD = '$#,##0;($#,##0);"-"'
USD2 = '$#,##0.00;($#,##0.00);"-"'
PCT = '0.0%;-0.0%;"-"'
INT = '#,##0;-#,##0;"-"'

SPEND_COLS = ["week_start", "week_num", "quarter", "advertiser_id", "advertiser_name", "vertical", "tier", "market",
              "agency_name", "csm_name", "product", "spend_usd", "impressions", "clicks", "conversions",
              "conversion_value_usd", "po_number", "billing_type"]
PRODUCTS = ["In-Feed Video", "Boosted Posts", "Search Placements", "Shoppable Video", "Auto-Campaigns", "Lift Studies"]


def rows(con, sql):
    cur = con.execute(sql)
    return [list(r) for r in cur.fetchall()]


def header(ws, row, labels, col=1):
    for i, h in enumerate(labels):
        c = ws.cell(row=row, column=col + i, value=h)
        c.font, c.fill = HEAD, HEAD_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)


def title(ws, text, sub):
    ws["A1"] = text
    ws["A1"].font = TITLE
    ws["A2"] = sub
    ws["A2"].font = NOTE
    ws.sheet_view.showGridLines = False


def widths(ws, w):
    for i, x in enumerate(w, start=1):
        ws.column_dimensions[get_column_letter(i)].width = x


def data_sheet(wb, name, cols, data, table_name, formats):
    ws = wb.create_sheet(name)
    header(ws, 1, cols)
    for r in data:
        ws.append(r)
    n = len(data) + 1
    for j, col in enumerate(cols, start=1):
        fmt = formats.get(col)
        for i in range(2, n + 1):
            c = ws.cell(row=i, column=j)
            c.font = BODY
            if fmt:
                c.number_format = fmt
    t = Table(displayName=table_name, ref=f"A1:{get_column_letter(len(cols))}{n}")
    t.tableStyleInfo = TableStyleInfo(name="TableStyleLight15", showRowStripes=True)
    ws.add_table(t)
    ws.freeze_panes = "A2"
    for j, col in enumerate(cols, start=1):
        ws.column_dimensions[get_column_letter(j)].width = max(11, min(26, len(col) + 4))
    return ws, n


def main(snapshot=True):
    con = sqlite3.connect(DB)
    wb = Workbook()

    # ---------------- Read Me ----------------
    ws = wb.active
    ws.title = "Read Me"
    title(ws, "Client Solutions Ops Desk", "Loopwave Ads (fictional) · North America Client Solutions · data as of Oct 4, 2026")
    lines = [
        ("What this is", "A reporting workbook for a client solutions team: spend and ad metrics, product adoption, purchase-order controls, Q3 delivery against commitments and a quarterly business review."),
        ("Data", "Synthetic. Generated by python/generate_data.py (seed 20271), cleaned in SQLite (sql/staging.sql). Internal QA sandbox accounts and the duplicated week-17 export are already removed from Spend Data."),
        ("Not affiliated", "Independent concept by Abdullah Al Mneni (TMU, Business Technology Management), built with Claude Code. Not affiliated with any ad platform."),
        ("How to read it", "Every reporting tab is formulas over the data tabs (SUMIFS / COUNTIFS / INDEX-MATCH), so changing a data row updates the whole workbook. Two tabs are real PivotTables."),
        ("Colour code", "Blue text = an input you can change (thresholds, the QBR account). Black = formula."),
    ]
    r = 4
    for k, v in lines:
        ws.cell(row=r, column=1, value=k).font = BOLD
        c = ws.cell(row=r, column=2, value=v)
        c.font = BODY
        c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.row_dimensions[r].height = 42
        r += 1
    r += 1
    ws.cell(row=r, column=1, value="Tab").font = BOLD
    ws.cell(row=r, column=2, value="What it answers").font = BOLD
    guide = [
        ("KPI Summary", "How did Q3 compare with Q2? Spend, impressions, CPM, CTR, CVR, CPA, ROAS."),
        ("Pivot Product x Quarter", "PivotTable: spend by product and quarter."),
        ("Pivot Vertical", "PivotTable: spend, conversions and conversion value by vertical."),
        ("Adoption", "Which products are clients actually using? (at least $500 in the last 4 weeks)"),
        ("Auto Funnel", "Auto-Campaigns launch: pitched, tested, adopted, sustained, by CSM."),
        ("PO Controls", "Is every dollar of spend covered by a valid purchase order?"),
        ("Q3 Attainment", "Which accounts delivered above or below their Q3 commitment?"),
        ("QBR", "One-account business review (change the account in cell B3)."),
        ("Metric Guide", "Definitions sales asks about, worked on this quarter's numbers."),
        ("Spend Data / PO Data / Commitments / Auto Accounts", "Source tables (Excel Tables, filterable)."),
    ]
    for k, v in guide:
        r += 1
        ws.cell(row=r, column=1, value=k).font = BODY
        ws.cell(row=r, column=2, value=v).font = BODY
    widths(ws, [34, 110])

    # ---------------- data tabs ----------------
    spend = rows(con, f"SELECT {', '.join(SPEND_COLS)} FROM fct_spend ORDER BY week_num, advertiser_id, product")
    for s in spend:
        s[0] = date.fromisoformat(s[0])
    fmts = {"week_start": "yyyy-mm-dd", "spend_usd": USD2, "conversion_value_usd": USD2,
            "impressions": INT, "clicks": INT, "conversions": INT}
    ws_sp, n_sp = data_sheet(wb, "Spend Data", SPEND_COLS, spend, "tblSpend", fmts)
    S = lambda col: f"'Spend Data'!${get_column_letter(SPEND_COLS.index(col) + 1)}$2:${get_column_letter(SPEND_COLS.index(col) + 1)}${n_sp}"

    po_cols = ["po_number", "advertiser_id", "advertiser_name", "agency_name", "quarter", "po_start", "po_end", "po_amount_usd"]
    pos = rows(con, """SELECT p.po_number, p.advertiser_id, a.advertiser_name, a.agency_name, p.quarter, p.po_start, p.po_end, p.po_amount_usd
                       FROM stg_purchase_orders p JOIN stg_advertisers a USING (advertiser_id) ORDER BY p.quarter, p.po_number""")
    for p in pos:
        p[5], p[6] = date.fromisoformat(p[5]), date.fromisoformat(p[6])
    ws_po, n_po = data_sheet(wb, "PO Data", po_cols, pos, "tblPO",
                             {"po_start": "yyyy-mm-dd", "po_end": "yyyy-mm-dd", "po_amount_usd": USD})

    com_cols = ["advertiser_id", "advertiser_name", "vertical", "tier", "csm_name", "committed_q3_usd"]
    com = rows(con, "SELECT advertiser_id, advertiser_name, vertical, tier, csm_name, committed_usd FROM mart_attainment ORDER BY advertiser_id")
    ws_cm, n_cm = data_sheet(wb, "Commitments", com_cols, com, "tblCommit", {"committed_q3_usd": USD})

    aa_cols = ["advertiser_id", "advertiser_name", "vertical", "tier", "csm_name", "pitched", "tested", "adopted", "sustained", "auto_spend_total"]
    aa = rows(con, f"SELECT {', '.join(aa_cols)} FROM mart_auto_accounts ORDER BY advertiser_id")
    ws_aa, n_aa = data_sheet(wb, "Auto Accounts", aa_cols, aa, "tblAuto", {"auto_spend_total": USD})
    A = lambda col: f"'Auto Accounts'!${get_column_letter(aa_cols.index(col) + 1)}$2:${get_column_letter(aa_cols.index(col) + 1)}${n_aa}"

    # ---------------- KPI Summary ----------------
    ws = wb.create_sheet("KPI Summary", 1)
    title(ws, "KPI Summary: Q3 vs Q2 2026", "Client accounts only. Formulas over Spend Data.")
    header(ws, 4, ["Metric", "2026-Q2", "2026-Q3", "Change", "How it is calculated"])
    ws["B4"], ws["C4"] = "2026-Q2", "2026-Q3"
    base = [
        ("Spend", "spend_usd", USD), ("Impressions", "impressions", INT), ("Clicks", "clicks", INT),
        ("Conversions", "conversions", INT), ("Conversion value", "conversion_value_usd", USD),
    ]
    r = 5
    for label, col, fmt in base:
        ws.cell(row=r, column=1, value=label).font = BODY
        for j, colq in ((2, "B"), (3, "C")):
            c = ws.cell(row=r, column=j, value=f'=SUMIFS({S(col)},{S("quarter")},{colq}$4)')
            c.number_format, c.font = fmt, BODY
        ws.cell(row=r, column=4, value=f"=IFERROR(C{r}/B{r}-1,0)").number_format = PCT
        ws.cell(row=r, column=5, value=f"Sum of {col}").font = NOTE
        r += 1
    ratios = [
        ("CPM (cost per 1,000 impressions)", "=IFERROR({c}5/{c}6*1000,0)", USD2, "Spend / impressions x 1,000"),
        ("CTR (click-through rate)", "=IFERROR({c}7/{c}6,0)", '0.00%', "Clicks / impressions"),
        ("CVR (conversion rate)", "=IFERROR({c}8/{c}7,0)", '0.00%', "Conversions / clicks"),
        ("CPA (cost per conversion)", "=IFERROR({c}5/{c}8,0)", USD2, "Spend / conversions"),
        ("ROAS (return on ad spend)", "=IFERROR({c}9/{c}5,0)", '0.00"x"', "Conversion value / spend"),
    ]
    for label, f, fmt, how in ratios:
        ws.cell(row=r, column=1, value=label).font = BODY
        for j, colq in ((2, "B"), (3, "C")):
            c = ws.cell(row=r, column=j, value=f.format(c=colq))
            c.number_format, c.font = fmt, BODY
        ws.cell(row=r, column=4, value=f"=IFERROR(C{r}/B{r}-1,0)").number_format = PCT
        ws.cell(row=r, column=5, value=how).font = NOTE
        r += 1
    for row in ws.iter_rows(min_row=5, max_row=r - 1, max_col=5):
        for c in row:
            c.border = THIN
    # product x quarter block feeding the chart
    r += 1
    ws.cell(row=r, column=1, value="Spend by product").font = BOLD
    hdr = r + 1
    header(ws, hdr, ["Product", "2026-Q2", "2026-Q3", "Change"])
    for i, p in enumerate(PRODUCTS):
        rr = hdr + 1 + i
        ws.cell(row=rr, column=1, value=p).font = BODY
        for j, colq in ((2, "B"), (3, "C")):
            c = ws.cell(row=rr, column=j, value=f'=SUMIFS({S("spend_usd")},{S("quarter")},{colq}${hdr},{S("product")},$A{rr})')
            c.number_format = USD
        ws.cell(row=rr, column=4, value=f"=IFERROR(C{rr}/B{rr}-1,0)").number_format = PCT
    ch = BarChart()
    ch.type, ch.title, ch.y_axis.title = "bar", "Spend by product", "USD"
    ch.add_data(Reference(ws, min_col=2, max_col=3, min_row=hdr, max_row=hdr + len(PRODUCTS)), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=hdr + 1, max_row=hdr + len(PRODUCTS)))
    ch.height, ch.width = 9, 16
    ws.add_chart(ch, "G4")
    # weekly trend
    wk = hdr + len(PRODUCTS) + 3
    ws.cell(row=wk - 1, column=1, value="Weekly spend").font = BOLD
    header(ws, wk, ["Week", "Week start", "Spend"])
    for w in range(1, 27):
        rr = wk + w
        ws.cell(row=rr, column=1, value=w)
        ws.cell(row=rr, column=2, value=f'=INDEX({S("week_start")},MATCH(A{rr},{S("week_num")},0))').number_format = "mmm d"
        ws.cell(row=rr, column=3, value=f'=SUMIFS({S("spend_usd")},{S("week_num")},A{rr})').number_format = USD
    lc = LineChart()
    lc.title, lc.height, lc.width = "Weekly spend (week-17 duplicate removed)", 8, 16
    lc.add_data(Reference(ws, min_col=3, min_row=wk, max_row=wk + 26), titles_from_data=True)
    lc.set_categories(Reference(ws, min_col=1, min_row=wk + 1, max_row=wk + 26))
    ws.add_chart(lc, "G24")
    widths(ws, [34, 16, 16, 10, 34])

