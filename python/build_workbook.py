    ws = wb.create_sheet("PO Controls", 4)
    title(ws, "Purchase-order controls", "One row per PO. Spend booked is matched on PO number and advertiser. Flags are formulas; red needs action this week.")
    cols = ["PO number", "Advertiser", "Agency", "Quarter", "PO end", "PO amount", "Spend booked", "Used",
            "Booked after PO end", "Advertisers on this PO", "Flag"]
    header(ws, 5, cols)
    PO = lambda col: f"'PO Data'!${get_column_letter(po_cols.index(col) + 1)}$2:${get_column_letter(po_cols.index(col) + 1)}${n_po}"
    for i in range(n_po - 1):
        rr = 6 + i
        src = i + 2
        ws.cell(row=rr, column=1, value=f"='PO Data'!A{src}")
        ws.cell(row=rr, column=2, value=f"='PO Data'!C{src}")
        ws.cell(row=rr, column=3, value=f"='PO Data'!D{src}")
        ws.cell(row=rr, column=4, value=f"='PO Data'!E{src}")
        ws.cell(row=rr, column=5, value=f"='PO Data'!G{src}").number_format = "yyyy-mm-dd"
        ws.cell(row=rr, column=6, value=f"='PO Data'!H{src}").number_format = USD
        ws.cell(row=rr, column=7, value=f"=SUMIFS({S('spend_usd')},{S('po_number')},A{rr},{S('advertiser_id')},'PO Data'!B{src})").number_format = USD
        ws.cell(row=rr, column=8, value=f"=IFERROR(G{rr}/F{rr},0)").number_format = PCT
        ws.cell(row=rr, column=9, value=f"=SUMIFS({S('spend_usd')},{S('po_number')},A{rr},{S('advertiser_id')},'PO Data'!B{src},{S('week_start')},\">\"&E{rr})").number_format = USD
        ws.cell(row=rr, column=10, value=f"=COUNTIF({PO('po_number')},A{rr})")
        ws.cell(row=rr, column=11, value=(f'=IF(J{rr}>1,"DUPLICATE PO",IF(AND(G{rr}>F{rr},I{rr}>0),"OVER + AFTER END",'
                                          f'IF(G{rr}>F{rr},"OVER PO",IF(I{rr}>0,"AFTER END","OK"))))'))
    endr = 5 + n_po - 1
    red = PatternFill("solid", fgColor="FBE3E8")
    amber = PatternFill("solid", fgColor="FFF1D6")
    ws.conditional_formatting.add(f"K6:K{endr}", FormulaRule(formula=[f'OR(K6="OVER PO",K6="DUPLICATE PO",K6="OVER + AFTER END")'], fill=red, font=Font(color="A3102F", bold=True)))
    ws.conditional_formatting.add(f"K6:K{endr}", FormulaRule(formula=[f'K6="AFTER END"'], fill=amber, font=Font(color="8A5A00", bold=True)))
    ws.conditional_formatting.add(f"H6:H{endr}", DataBarRule(start_type="num", start_value=0, end_type="num", end_value=1.4, color=ACCENT))
    ws.auto_filter.ref = f"A5:K{endr}"
    ws.freeze_panes = "B6"
    ws["M5"], ws["N5"] = "Flag", "POs"
    ws["M5"].font = ws["N5"].font = BOLD
    for i, f in enumerate(["DUPLICATE PO", "OVER + AFTER END", "OVER PO", "AFTER END", "OK"]):
        ws.cell(row=6 + i, column=13, value=f)
        ws.cell(row=6 + i, column=14, value=f'=COUNTIF($K$6:$K${endr},M{6 + i})')
    ws["M12"] = "Missing PO numbers (invoice-billed spend with no PO)"
    ws["M12"].font = BOLD
    ws["M13"] = f'=SUMIFS({S("spend_usd")},{S("billing_type")},"invoice",{S("po_number")},"")'
    ws["M13"].number_format = USD
    widths(ws, [11, 24, 20, 10, 11, 13, 14, 9, 14, 12, 18, 2, 30, 8])

    # ---------------- Q3 Attainment ----------------
    ws = wb.create_sheet("Q3 Attainment", 5)
    title(ws, "Q3 delivery vs commitment", "Commitment = the quarterly spend each account agreed with sales. Thresholds in blue.")
    ws["A3"], ws["B3"], ws["C3"], ws["D3"] = "Under below", 0.9, "Over above", 1.1
    for c in ("B3", "D3"):
        ws[c].font, ws[c].number_format = INPUT_FONT, PCT
    header(ws, 5, ["Advertiser ID", "Advertiser", "Vertical", "CSM", "Committed", "Delivered", "Attainment", "Status"])
    for i in range(n_cm - 1):
        rr, src = 6 + i, i + 2
