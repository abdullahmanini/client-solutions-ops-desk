# ---------------------------------------------------------------- pivot XML
def add_pivots(path, sheetnames, n_rows, con):
    distinct = {c: [r[0] for r in rows(con, f"SELECT DISTINCT {c} FROM fct_spend ORDER BY {c}")] for c in ("quarter", "vertical", "product")}
    fields_xml = []
    for c in SPEND_COLS:
        if c in distinct:
            items = "".join(f'<s v="{escape(v)}"/>' for v in distinct[c])
            fields_xml.append(f'<cacheField name="{c}" numFmtId="0"><sharedItems count="{len(distinct[c])}">{items}</sharedItems></cacheField>')
        else:
            fields_xml.append(f'<cacheField name="{c}" numFmtId="0"><sharedItems/></cacheField>')
    cache = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
             '<pivotCacheDefinition xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
             'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
             'saveData="0" refreshOnLoad="1" createdVersion="6" refreshedVersion="6" minRefreshableVersion="3" recordCount="0">'
             f'<cacheSource type="worksheet"><worksheetSource ref="A1:{get_column_letter(len(SPEND_COLS))}{n_rows}" sheet="Spend Data"/></cacheSource>'
             f'<cacheFields count="{len(SPEND_COLS)}">{"".join(fields_xml)}</cacheFields></pivotCacheDefinition>')

    def pivot_fields(axes, data_cols):
        out = []
        for c in SPEND_COLS:
            if c in axes:
                n = len(distinct[c])
                items = "".join(f'<item x="{i}"/>' for i in range(n)) + '<item t="default"/>'
                out.append(f'<pivotField axis="{axes[c]}" showAll="0"><items count="{n + 1}">{items}</items></pivotField>')
            elif c in data_cols:
                out.append('<pivotField dataField="1" showAll="0"/>')
            else:
                out.append('<pivotField showAll="0"/>')
        return f'<pivotFields count="{len(SPEND_COLS)}">{"".join(out)}</pivotFields>'

    idx = SPEND_COLS.index
    nq, nv, npr = len(distinct["quarter"]), len(distinct["vertical"]), len(distinct["product"])
    pt1 = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
           '<pivotTableDefinition xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" name="PivotProductQuarter" cacheId="1" '
           'applyNumberFormats="0" applyBorderFormats="0" applyFontFormats="0" applyPatternFormats="0" applyAlignmentFormats="0" applyWidthHeightFormats="1" '
           'dataCaption="Values" updatedVersion="6" minRefreshableVersion="3" useAutoFormatting="1" itemPrintTitles="1" createdVersion="6" indent="0" outline="1" outlineData="1">'
           f'<location ref="A3:D{4 + npr + 1}" firstHeaderRow="1" firstDataRow="2" firstDataCol="1"/>'
           + pivot_fields({"product": "axisRow", "quarter": "axisCol"}, {"spend_usd"}) +
           f'<rowFields count="1"><field x="{idx("product")}"/></rowFields>'
           f'<rowItems count="{npr + 1}">' + "".join(f'<i><x v="{i}"/></i>' if i else '<i><x/></i>' for i in range(npr)) + '<i t="grand"><x/></i></rowItems>'
           f'<colFields count="1"><field x="{idx("quarter")}"/></colFields>'
           f'<colItems count="{nq + 1}">' + "".join(f'<i><x v="{i}"/></i>' if i else '<i><x/></i>' for i in range(nq)) + '<i t="grand"><x/></i></colItems>'
           f'<dataFields count="1"><dataField name="Spend (USD)" fld="{idx("spend_usd")}" baseField="0" baseItem="0" numFmtId="3"/></dataFields>'
           '<pivotTableStyleInfo name="PivotStyleMedium2" showRowHeaders="1" showColHeaders="1" showRowStripes="0" showColStripes="0" showLastColumn="1"/>'
           '</pivotTableDefinition>')
    pt2 = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
           '<pivotTableDefinition xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" name="PivotVertical" cacheId="1" '
           'applyNumberFormats="0" applyBorderFormats="0" applyFontFormats="0" applyPatternFormats="0" applyAlignmentFormats="0" applyWidthHeightFormats="1" '
           'dataCaption="Values" updatedVersion="6" minRefreshableVersion="3" useAutoFormatting="1" itemPrintTitles="1" createdVersion="6" indent="0" outline="1" outlineData="1">'
           f'<location ref="A3:D{4 + nv}" firstHeaderRow="0" firstDataRow="1" firstDataCol="1"/>'
           + pivot_fields({"vertical": "axisRow"}, {"spend_usd", "conversions", "conversion_value_usd"}) +
           f'<rowFields count="1"><field x="{idx("vertical")}"/></rowFields>'
           f'<rowItems count="{nv + 1}">' + "".join(f'<i><x v="{i}"/></i>' if i else '<i><x/></i>' for i in range(nv)) + '<i t="grand"><x/></i></rowItems>'
           '<colFields count="1"><field x="-2"/></colFields>'
           '<colItems count="3"><i><x/></i><i i="1"><x v="1"/></i><i i="2"><x v="2"/></i></colItems>'
           '<dataFields count="3">'
           f'<dataField name="Spend (USD)" fld="{idx("spend_usd")}" baseField="0" baseItem="0" numFmtId="3"/>'
           f'<dataField name="Conversions" fld="{idx("conversions")}" baseField="0" baseItem="0" numFmtId="3"/>'
           f'<dataField name="Conversion value (USD)" fld="{idx("conversion_value_usd")}" baseField="0" baseItem="0" numFmtId="3"/>'
           '</dataFields>'
           '<pivotTableStyleInfo name="PivotStyleMedium2" showRowHeaders="1" showColHeaders="1" showRowStripes="0" showColStripes="0" showLastColumn="1"/>'
           '</pivotTableDefinition>')

    tmp = path.with_suffix(".tmp.xlsx")
    shutil.move(path, tmp)
    with zipfile.ZipFile(tmp) as zin, zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zout:
        names = zin.namelist()
        wb_rels = zin.read("xl/_rels/workbook.xml.rels").decode()
        wb_xml = zin.read("xl/workbook.xml").decode()
        # map sheet name -> sheet xml path
        rid_target = {}
        for rel in re.findall(r"<Relationship [^>]*>", wb_rels):
            rid = re.search(r'Id="([^"]+)"', rel).group(1)
            rid_target[rid] = re.sub(r"^/?(xl/)?", "", re.search(r'Target="([^"]+)"', rel).group(1))
        sheet_file = {}
        for name, rid in re.findall(r'<sheet name="([^"]+)" sheetId="\d+" (?:state="\w+" )?r:id="(rId\d+)"', wb_xml):
            sheet_file[name.replace("&amp;", "&")] = "xl/" + rid_target[rid]
        targets = {"Pivot Product x Quarter": ("pivotTable1.xml", pt1), "Pivot Vertical": ("pivotTable2.xml", pt2)}
        wb_rels = wb_rels.replace("</Relationships>", '<Relationship Id="rIdPC1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/pivotCacheDefinition" Target="pivotCache/pivotCacheDefinition1.xml"/></Relationships>')
        # schema order: ... definedNames, calcPr, oleSize, customWorkbookViews, pivotCaches ...
        pc = '<pivotCaches><pivotCache cacheId="1" r:id="rIdPC1"/></pivotCaches>'
        m = re.search(r"<calcPr[^>]*/>", wb_xml)
        if m:
            wb_xml = wb_xml[:m.end()] + pc + wb_xml[m.end():]
        else:
            anchor = "</definedNames>" if "</definedNames>" in wb_xml else "</sheets>"
            wb_xml = wb_xml.replace(anchor, anchor + pc, 1)
        ct = zin.read("[Content_Types].xml").decode()
        ct = ct.replace("</Types>",
                        '<Override PartName="/xl/pivotCache/pivotCacheDefinition1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.pivotCacheDefinition+xml"/>'
                        '<Override PartName="/xl/pivotTables/pivotTable1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.pivotTable+xml"/>'
                        '<Override PartName="/xl/pivotTables/pivotTable2.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.pivotTable+xml"/></Types>')
        sheet_rels = {}
        for sname, (pt_name, _) in targets.items():
            sf = sheet_file[sname]
            rel_path = sf.replace("worksheets/", "worksheets/_rels/") + ".rels"
            existing = zin.read(rel_path).decode() if rel_path in names else '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"></Relationships>'
            sheet_rels[rel_path] = existing.replace("</Relationships>", f'<Relationship Id="rIdPT1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/pivotTable" Target="../pivotTables/{pt_name}"/></Relationships>')
        for n in names:
            if n in ("xl/_rels/workbook.xml.rels", "xl/workbook.xml", "[Content_Types].xml") or n in sheet_rels:
                continue
            zout.writestr(n, zin.read(n))
        zout.writestr("xl/_rels/workbook.xml.rels", wb_rels)
        zout.writestr("xl/workbook.xml", wb_xml)
        zout.writestr("[Content_Types].xml", ct)
        for k, v in sheet_rels.items():
            zout.writestr(k, v)
        zout.writestr("xl/pivotCache/pivotCacheDefinition1.xml", cache)
        for _, (pt_name, xml) in targets.items():
            zout.writestr(f"xl/pivotTables/{pt_name}", xml)
            zout.writestr(f"xl/pivotTables/_rels/{pt_name}.rels",
                          '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                          '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/pivotCacheDefinition" Target="../pivotCache/pivotCacheDefinition1.xml"/></Relationships>')
    tmp.unlink()


