"""Build the Excel workbook: data tabs, formula-driven reporting tabs, charts and two PivotTables.

openpyxl cannot create PivotTables, so this script writes the pivot cache and pivot table XML
directly into the saved file with refreshOnLoad="1"; Excel builds the pivots when the file opens.
python/finalize_workbook.applescript then opens the file in Excel, recalculates and saves, so every
formula and pivot has cached values (needed for previewers and Google Sheets import).

Run: python3 python/build_workbook.py   (after pipeline.py)
"""
